test('MA12: transport response body and signature callback share one eight-second deadline and never return late success',async(context)=>{
  context.mock.timers.enable({apis:['setTimeout']});
  for(const mode of ['transport','body','signature']) {
    let started!:()=>void,finish!:(actor:MfaActor)=>void,aborted=false,cancelled=false,calls=0;
    const ready=new Promise<void>(resolve=>{started=resolve;});
    const transport:typeof fetch=async(_url,options)=>{
      calls++;options?.signal?.addEventListener('abort',()=>{aborted=true;},{once:true});
      if(mode==='transport') {started();return new Promise<Response>(()=>{});}
      if(mode==='body') return new Response(new ReadableStream<Uint8Array>({pull(){started();return new Promise<void>(()=>{});},cancel(){cancelled=true;}}),{headers:{'content-type':'application/json'}});
      return json(verified());
    };
    const pending=verify(transport,mode==='signature'?async()=>{started();return new Promise(resolve=>{finish=resolve;});}:verifyAccess);
    await ready;await setImmediate();const rejected=assert.rejects(pending,check('MFA_UNCONFIRMED'));context.mock.timers.tick(8000);await rejected;
    assert.equal(calls,1);assert.equal(aborted,true);if(mode==='body') assert.equal(cancelled,true);
    if(mode==='signature') {finish(actor);await setImmediate();}
  }
});
