import assert from 'node:assert/strict';
import { test } from 'node:test';
import { totpQrSource } from '../../../apps/admin/src/features/management/qr.ts';

// Official goqrsvg/SVGo structure and observed payload size, without a real TOTP secret.
function officialShape(bytes: number) {
  const start = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by SVGo -->\n<svg width="123" height="123" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">\n';
  const rect = '<rect x="12" y="12" width="3" height="3" style="fill:black;stroke:none"/>\n';
  const end = '</svg>\n';
  const count = Math.floor((bytes - start.length - end.length) / rect.length);
  const geometry = start + rect.repeat(count);
  return geometry + ' '.repeat(bytes - geometry.length - end.length) + end;
}

test('AQ01: official XML/comments and 362632-byte rect geometry produce a local SVG image', () => {
  const svg = officialShape(362632);
  assert.equal(new TextEncoder().encode(svg).byteLength, 362632);
  assert.ok((svg.match(/<rect /g) ?? []).length > 4000);
  const source = totpQrSource(svg);
  assert.ok(source); assert.ok(source.startsWith('data:image/svg+xml;charset=utf-8,'));
  const image = decodeURIComponent(source.slice(source.indexOf(',') + 1));
  assert.ok(image.startsWith('<svg ')); assert.ok(!image.includes('<?xml')); assert.ok(!image.includes('<!--'));
  assert.equal(totpQrSource('data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64')), source);
});

test('AQ02: the 768 KiB decoded-byte boundary accepts official geometry and rejects oversized raw/encoded images', () => {
  assert.ok(totpQrSource(officialShape(768 * 1024)));
  const oversized = officialShape(768 * 1024 + 1);
  assert.equal(totpQrSource(oversized), null);
  assert.equal(totpQrSource('data:image/svg+xml;base64,' + Buffer.from(oversized).toString('base64')), null);
  assert.equal(totpQrSource('<svg xmlns="http://www.w3.org/2000/svg"><rect width="3" height="3"/></svg>' + '中'.repeat(768 * 1024 / 3)), null);
});

test('AQ03: active markup, external references, unsafe CSS, entities and processing instructions remain rejected', () => {
  const wrap = (body: string) => '<?xml version="1.0"?>\n<!-- official comment -->\n<svg xmlns="http://www.w3.org/2000/svg">' + body + '</svg>';
  for (const body of ['<script>alert(1)</script>', '<rect onload="alert(1)"/>', '<image href="https://external.invalid/secret"/>',
    '<use href="#external"/>', '<foreignObject/>', '<rect style="fill:url(https://external.invalid);stroke:none"/>',
    '<rect style="fill:black;stroke:none" data-url="https://external.invalid"/>', '<rect fill="url(example)"/>',
    '<?xml-stylesheet href="https://external.invalid"?><rect/>', '<!DOCTYPE svg><rect/>', '<rect/>&external;', '<svg><rect/></svg>text']) {
    assert.equal(totpQrSource(wrap(body)), null, body);
  }
  assert.equal(totpQrSource('<?xml version="1.1"?><svg><rect/></svg>'), null);
  assert.equal(totpQrSource('https://external.invalid/qr.svg'), null);
  assert.equal(totpQrSource('<svg><rect/>\u0000</svg>'), null);
});
